    @classmethod
    def _extract_and_parse_document(cls, file_path: Path) -> Dict[str, Any]:
        """Extracts text and candidate fields from a single shipment document."""
        doc_result = document_extractor.extract_text(file_path)
        is_readable = doc_result.has_text and not doc_result.ocr_required
        status = "readable" if is_readable else "unreadable"

        text = doc_result.text_content
        fields: Dict[str, Any] = {}

        if not is_readable or not text.strip():
            return {
                "filename": file_path.name,
                "path": str(file_path),
                "status": "unreadable",
                "raw_text": "",
                "fields": {}
            }

        # 1. Document Type Detection
        doc_type = "Shipment Document"
        upper_text = text.upper()
        if "BILL OF LADING" in upper_text or "B/L" in upper_text or "WAYBILL" in upper_text:
            doc_type = "Bill of Lading"
        elif "COMMERCIAL INVOICE" in upper_text or "INVOICE" in upper_text:
            doc_type = "Commercial Invoice"
        elif "PACKING LIST" in upper_text or "PACKING SLIP" in upper_text:
            doc_type = "Packing List"
        elif "CERTIFICATE OF ORIGIN" in upper_text:
            doc_type = "Certificate of Origin"

        fields["document_type"] = {"value": doc_type, "evidence": doc_type}

        # 2. Reference / Invoice Number
        ref_match = re.search(
            r'(?:Invoice(?:\s*(?:No\.?|Number|#))?|INV(?:\s*#)?|Bill\s*of\s*Lading(?:\s*No\.?)?|B/L(?:\s*No\.?)?|Ref(?:\.|erence)?|Booking(?:\s*No\.?)?)[\t ]*[:#][\t ]*([A-Z0-9\-_/]+)',
            text,
            re.IGNORECASE
        )
        if ref_match:
            fields["reference_number"] = {
                "value": ref_match.group(1).strip(),
                "evidence": ref_match.group(0).strip()
            }

        # 3. Currency
        curr_match = re.search(r'\b(USD|EUR|GBP|JPY|CAD|AUD|CHF|CNY|INR)\b|\$|€|£', text)
        if curr_match:
            raw_c = curr_match.group(0)
            c_norm = {
                "$": "USD", "€": "EUR", "£": "GBP"
            }.get(raw_c, raw_c)
            fields["currency"] = {
                "value": c_norm,
                "evidence": curr_match.group(0)
            }

        # 4. Monetary Total
        total_match = re.search(
            r'(?:Total\s*Amount|Grand\s*Total|Invoice\s*Total|Total(?:\s*USD|\s*EUR)?|Invoice\s*Amount)[:\s]+(?:USD|EUR|GBP|\$|€|£)?\s*([0-9]+(?:,[0-9]{3})*(?:\.[0-9]{1,2})?|[0-9]+(?:\.[0-9]{1,2})?)',
            text,
            re.IGNORECASE
        )
        if total_match:
            num_clean = total_match.group(1).replace(",", "")
            try:
                dec_val = Decimal(num_clean)
                fields["total_amount"] = {
                    "value": str(dec_val),
                    "decimal": dec_val,
                    "evidence": total_match.group(0).strip()
                }
            except InvalidOperation:
                pass

        # 5. Gross Weight
        gw_match = re.search(
            r'(?:Gross\s*Weight|G\.W\.|GW)[:\s]+([0-9]+(?:\.[0-9]+)?)\s*(kg|kgs|kilograms|lbs|pounds|mt|metric tons)?',
            text,
            re.IGNORECASE
        )
        if gw_match:
            val_str = gw_match.group(1)
            raw_unit = (gw_match.group(2) or "kg").lower()
            unit_norm = "kg" if "kg" in raw_unit else ("lbs" if "lb" in raw_unit else raw_unit)
            try:
                dec_val = Decimal(val_str)
                fields["gross_weight"] = {
                    "value": f"{dec_val} {unit_norm}",
                    "decimal": dec_val,
                    "unit": unit_norm,
                    "evidence": gw_match.group(0).strip()
                }
            except InvalidOperation:
                pass

        # 6. Net Weight
        nw_match = re.search(
            r'(?:Net\s*Weight|N\.W\.|NW)[:\s]+([0-9]+(?:\.[0-9]+)?)\s*(kg|kgs|kilograms|lbs|pounds|mt|metric tons)?',
            text,
            re.IGNORECASE
        )
        if nw_match:
            val_str = nw_match.group(1)
            raw_unit = (nw_match.group(2) or "kg").lower()
            unit_norm = "kg" if "kg" in raw_unit else ("lbs" if "lb" in raw_unit else raw_unit)
            try:
                dec_val = Decimal(val_str)
                fields["net_weight"] = {
                    "value": f"{dec_val} {unit_norm}",
                    "decimal": dec_val,
                    "unit": unit_norm,
                    "evidence": nw_match.group(0).strip()
                }
            except InvalidOperation:
                pass

        # 7. Package Count
        pkg_match = re.search(
            r'(?:Package[s]?|Packages\s*Count|Total\s*Packages|Quantity|Qty|Cartons|Boxes|Pallets)[:\s]+([0-9]+)\s*(pkgs|packages|cartons|boxes|ctns|pallets)?',
            text,
            re.IGNORECASE
        )
        if pkg_match:
            val_str = pkg_match.group(1)
            unit_str = pkg_match.group(2) or "packages"
            try:
                dec_val = Decimal(val_str)
                fields["package_count"] = {
                    "value": f"{dec_val} {unit_str}",
                    "decimal": dec_val,
                    "unit": unit_str,
                    "evidence": pkg_match.group(0).strip()
                }
            except InvalidOperation:
                pass

        # 8. Shipper / Exporter
        shipper_match = re.search(
            r'(?:Shipper|Exporter|Consignor)[:\s]+([^\n\r]+)',
            text,
            re.IGNORECASE
        )
        if shipper_match:
            fields["shipper"] = {
                "value": shipper_match.group(1).strip()[:100],
                "evidence": shipper_match.group(0).strip()[:120]
            }

        # 9. Consignee / Buyer
        consignee_match = re.search(
            r'(?:Consignee|Buyer|Importer)[:\s]+([^\n\r]+)',
            text,
            re.IGNORECASE
        )
        if consignee_match:
            fields["consignee"] = {
                "value": consignee_match.group(1).strip()[:100],
                "evidence": consignee_match.group(0).strip()[:120]
            }

        return {
            "filename": file_path.name,
            "path": str(file_path),
            "status": status,
            "raw_text": text,
            "fields": fields
        }

    @classmethod
    def _cross_compare_documents(cls, docs: List[Dict[str, Any]]) -> List[Dict[str, Any]]:
        """Cross-compares extracted fields across documents using decimal arithmetic and strict unit/currency rules."""
        findings: List[Dict[str, Any]] = []

        # Check for unreadable documents first
        for doc in docs:
            if doc["status"] == "unreadable":
                findings.append({
                    "field_name": "document_readability",
                    "status": "unreadable",
                    "source_documents": [doc["filename"]],
                    "extracted_values": {doc["filename"]: "Unreadable or blank document"},
                    "normalized_value": None,
                    "difference": None,
                    "tolerance": None,
                    "severity": "high",
                    "confidence": 1.0,
                    "evidence_reference": f"Document '{doc['filename']}' could not be extracted (possibly image-only scan without OCR).",
                    "recommended_action": "Rescan document at high resolution or obtain digital text PDF/DOCX."
                })

        readable_docs = [d for d in docs if d["status"] == "readable"]
        if len(readable_docs) < 2:
            return findings

        # Fields to audit across documents
        candidate_fields = [
            "reference_number",
            "currency",
            "total_amount",
            "gross_weight",
            "net_weight",
            "package_count",
            "shipper",
            "consignee"
        ]

        for field_name in candidate_fields:
            cls._compare_single_field(field_name, readable_docs, findings)

        return findings

    @classmethod
    def _compare_single_field(
        cls,
        field_name: str,
        docs: List[Dict[str, Any]],
        findings: List[Dict[str, Any]]
    ) -> None:
        """Compares a specific field across readable documents."""
        extracted_by_doc: Dict[str, Dict[str, Any]] = {}
        for d in docs:
            if field_name in d["fields"]:
                extracted_by_doc[d["filename"]] = d["fields"][field_name]

        # Case 1: Field not present in any document
        if not extracted_by_doc:
            return

        # Case 2: Field missing in some documents where expected
        if len(extracted_by_doc) < len(docs):
            missing_docs = [d["filename"] for d in docs if d["filename"] not in extracted_by_doc]
            present_docs = list(extracted_by_doc.keys())
            findings.append({
                "field_name": field_name,
                "status": "missing",
                "source_documents": [d["filename"] for d in docs],
                "extracted_values": {
                    d["filename"]: extracted_by_doc[d["filename"]]["value"]
                    if d["filename"] in extracted_by_doc else "NOT PRESENT"
                    for d in docs
                },
                "normalized_value": extracted_by_doc[present_docs[0]]["value"],
                "difference": None,
                "tolerance": None,
                "severity": "info" if field_name in ("currency", "total_amount", "net_weight") else "low",
                "confidence": 0.95,
                "evidence_reference": f"Field '{field_name}' found in {present_docs} but absent in {missing_docs}.",
                "recommended_action": f"Verify if '{field_name}' is required in {missing_docs} per trade terms."
            })
            # Continue comparison between documents that DO have the field
            if len(extracted_by_doc) < 2:
                return

        # Case 3: Field is present in multiple documents. Let's compare them!
        doc_names = list(extracted_by_doc.keys())

        # Sub-case A: Numeric fields with Decimal comparison (total_amount, gross_weight, net_weight, package_count)
        if field_name in ("total_amount", "gross_weight", "net_weight", "package_count"):
            cls._compare_decimal_field(field_name, extracted_by_doc, findings)
            return

        # Sub-case B: Text / Code fields (reference_number, currency, shipper, consignee)
        values = [extracted_by_doc[d]["value"].strip().upper() for d in doc_names]
        first_val = values[0]
        all_match = all(v == first_val for v in values)

        evidence_str = "; ".join(
            f"{d}: '{extracted_by_doc[d]['evidence']}'" for d in doc_names
        )

        if all_match:
            findings.append({
                "field_name": field_name,
                "status": "verified",
                "source_documents": doc_names,
                "extracted_values": {d: extracted_by_doc[d]["value"] for d in doc_names},
                "normalized_value": extracted_by_doc[doc_names[0]]["value"],
                "difference": "0",
                "tolerance": "0",
                "severity": "info",
                "confidence": 1.0,
                "evidence_reference": evidence_str,
                "recommended_action": "Values match exactly across all documents. Verified."
            })
        else:
            findings.append({
                "field_name": field_name,
                "status": "inconsistent",
                "source_documents": doc_names,
                "extracted_values": {d: extracted_by_doc[d]["value"] for d in doc_names},
                "normalized_value": None,
                "difference": "Mismatch",
                "tolerance": "0",
                "severity": "high",
                "confidence": 0.98,
                "evidence_reference": evidence_str,
                "recommended_action": f"Reconcile contradictory {field_name} across shipping documents before customs submission."
            })

    @classmethod
    def _compare_decimal_field(
        cls,
        field_name: str,
        extracted_by_doc: Dict[str, Dict[str, Any]],
        findings: List[Dict[str, Any]]
    ) -> None:
        """Performs exact decimal arithmetic comparison, unit validation, and tolerance checks."""
        doc_names = list(extracted_by_doc.keys())

        # 1. Unit / Currency Consistency Check
        if field_name in ("gross_weight", "net_weight", "package_count"):
            units = [extracted_by_doc[d].get("unit", "") for d in doc_names]
            if len(set(units)) > 1:
                # Unit mismatch!
                findings.append({
                    "field_name": f"{field_name}_unit",
                    "status": "inconsistent",
                    "source_documents": doc_names,
                    "extracted_values": {d: extracted_by_doc[d]["value"] for d in doc_names},
                    "normalized_value": None,
                    "difference": f"Unit conflict: {units}",
                    "tolerance": "0",
                    "severity": "high",
                    "confidence": 1.0,
                    "evidence_reference": "; ".join(f"{d}: {extracted_by_doc[d]['evidence']}" for d in doc_names),
                    "recommended_action": f"Convert all documents to uniform units ({units[0]}) to avoid customs weight discrepancies."
                })
                return

        # 2. Decimal Arithmetic
        decimals: List[Tuple[str, Decimal]] = []
        for d in doc_names:
            dec = extracted_by_doc[d].get("decimal")
            if dec is not None:
                decimals.append((d, dec))

        if len(decimals) < 2:
            return

        base_doc, base_val = decimals[0]
        max_diff = Decimal("0")
        diff_pairs: List[str] = []

        for other_doc, other_val in decimals[1:]:
            diff = abs(other_val - base_val)
            if diff > max_diff:
                max_diff = diff
            if diff > Decimal("0"):
                diff_pairs.append(f"{other_doc} differs from {base_doc} by {diff}")

        evidence_str = "; ".join(
            f"{d}: '{extracted_by_doc[d]['evidence']}'" for d in doc_names
        )

        tolerance = Decimal("0.00")

        if max_diff == Decimal("0"):
            findings.append({
                "field_name": field_name,
                "status": "verified",
                "source_documents": doc_names,
                "extracted_values": {d: extracted_by_doc[d]["value"] for d in doc_names},
                "normalized_value": str(base_val),
                "difference": "0.00",
                "tolerance": str(tolerance),
                "severity": "info",
                "confidence": 1.0,
                "evidence_reference": evidence_str,
                "recommended_action": "Numeric quantities match identically across all documents. Verified."
            })
        else:
            findings.append({
                "field_name": field_name,
                "status": "inconsistent",
                "source_documents": doc_names,
                "extracted_values": {d: extracted_by_doc[d]["value"] for d in doc_names},
                "normalized_value": str(base_val),
                "difference": str(max_diff),
                "tolerance": str(tolerance),
                "severity": "high" if field_name in ("package_count", "total_amount") else "medium",
                "confidence": 1.0,
                "evidence_reference": evidence_str,
                "recommended_action": f"Critical variance of {max_diff} detected ({'; '.join(diff_pairs)}). Amend shipping papers to match."
            })
