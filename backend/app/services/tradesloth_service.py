"""TradeSloth Document Auditor Service.

Multi-document cross-audit for shipping and trade documentation (PDF, DOCX, XLSX, TXT).
Performs deterministic field extraction, unit/currency validation, decimal arithmetic comparison,
discrepancy detection, and audit report generation with strict legal limitations.
"""

from decimal import Decimal, InvalidOperation
import json
import logging
from pathlib import Path
import re
import uuid
from datetime import datetime, timezone
from typing import Any, Dict, List, Optional, Tuple

from backend.app.db.session import get_db
from backend.app.services.audit_service import audit_service
from backend.app.services.document_extractor import document_extractor
from backend.app.services.path_service import path_service

logger = logging.getLogger(__name__)

LEGAL_DISCLAIMER = (
    "LEGAL DISCLAIMER: This audit report is generated by automated local document extraction "
    "and deterministic cross-comparison. It does NOT certify legal, customs, or regulatory compliance "
    "with international trade laws, export controls, or customs declarations. All findings must be "
    "manually inspected and validated by a licensed customs broker or freight forwarding professional."
)


class TradeSlothService:
    """Audits shipment documents for discrepancies in reference numbers, quantities, weights, and monetary values."""

    @classmethod
    def audit_documents(
        cls,
        document_paths: List[str],
        title: Optional[str] = None
    ) -> Dict[str, Any]:
        """Runs a complete audit across 2 or more shipping documents.

        Validates paths, extracts content, extracts candidate fields,
        performs decimal comparisons, records findings, and creates an audit record.
        """
        if len(document_paths) < 1:
            raise ValueError("At least 1 shipment document is required for an audit.")

        # 1. Validate all document paths exist and are within approved roots
        validated_files: List[Path] = []
        for p in document_paths:
            v_path = path_service.validate_path(p)
            if not v_path.is_file():
                raise ValueError(f"Path is not a regular file: {p}")
            validated_files.append(v_path)

        audit_id = str(uuid.uuid4())
        now_utc = datetime.now(timezone.utc).isoformat()
        audit_title = title or f"Shipment Audit {now_utc[:10]} ({len(validated_files)} docs)"

        # 2. Extract text from each document
        extracted_docs: List[Dict[str, Any]] = []
        for file_path in validated_files:
            doc_data = cls._extract_and_parse_document(file_path)
            extracted_docs.append(doc_data)

        # 3. Cross-compare extracted fields across all documents
        findings = cls._cross_compare_documents(extracted_docs)

        # Determine overall audit status (discrepancies exist only if there are contradictory values)
        has_inconsistency = any(f.get("status") == "inconsistent" for f in findings)
        overall_status = "discrepancies_found" if has_inconsistency else "clean"

        summary = {
            "total_documents": len(extracted_docs),
            "documents": [
                {
                    "filename": d["filename"],
                    "path": d["path"],
                    "document_type": d["fields"].get("document_type", {}).get("value", "Unknown"),
                    "extraction_status": d["status"]
                }
                for d in extracted_docs
            ],
            "total_findings": len(findings),
            "discrepancies": sum(1 for f in findings if f["status"] == "inconsistent"),
            "verified": sum(1 for f in findings if f["status"] == "verified"),
            "unreadable": sum(1 for f in findings if f["status"] == "unreadable"),
            "missing": sum(1 for f in findings if f["status"] == "missing"),
            "legal_disclaimer": LEGAL_DISCLAIMER
        }

        # 4. Save audit and findings in SQLite
        with get_db() as conn:
            cursor = conn.cursor()
            cursor.execute(
                """
                INSERT INTO shipment_audits (id, title, status, created_at, summary_json)
                VALUES (?, ?, ?, ?, ?)
                """,
                (audit_id, audit_title, overall_status, now_utc, json.dumps(summary))
            )

            for f in findings:
                finding_id = str(uuid.uuid4())
                cursor.execute(
                    """
                    INSERT INTO shipment_findings (
                        id, audit_id, field_name, source_documents_json, extracted_values_json,
                        normalized_value, difference, tolerance, severity, confidence,
                        evidence_reference, recommended_action
                    )
                    VALUES (?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?, ?)
                    """,
                    (
                        finding_id,
                        audit_id,
                        f["field_name"],
                        json.dumps(f["source_documents"]),
                        json.dumps(f["extracted_values"]),
                        f.get("normalized_value"),
                        f.get("difference"),
                        f.get("tolerance"),
                        f["severity"],
                        f.get("confidence", 1.0),
                        f["evidence_reference"],
                        f["recommended_action"]
                    )
                )

        # 5. Record immutable audit log
        audit_service.log(
            action="tradesloth_audit_completed",
            module="tradesloth",
            actor="user",
            details=f"Audited {len(validated_files)} documents: {overall_status} with {len(findings)} findings.",
            success=True
        )

        return {
            "id": audit_id,
            "title": audit_title,
            "status": overall_status,
            "created_at": now_utc,
            "summary": summary,
            "findings": findings
        }

    @classmethod
    def get_audit(cls, audit_id: str) -> Optional[Dict[str, Any]]:
        """Retrieves an existing audit and its associated discrepancy findings."""
        with get_db() as conn:
            cursor = conn.cursor()
            cursor.execute(
                "SELECT id, title, status, created_at, summary_json FROM shipment_audits WHERE id = ?",
                (audit_id,)
            )
            row = cursor.fetchone()
            if not row:
                return None

            audit = {
                "id": row[0],
                "title": row[1],
                "status": row[2],
                "created_at": row[3],
                "summary": json.loads(row[4]),
                "findings": []
            }

            cursor.execute(
                """
                SELECT id, field_name, source_documents_json, extracted_values_json,
                       normalized_value, difference, tolerance, severity, confidence,
                       evidence_reference, recommended_action
                FROM shipment_findings
                WHERE audit_id = ?
                """,
                (audit_id,)
            )
            findings_rows = cursor.fetchall()
            for f in findings_rows:
                audit["findings"].append({
                    "id": f[0],
                    "field_name": f[1],
                    "source_documents": json.loads(f[2]),
                    "extracted_values": json.loads(f[3]),
                    "normalized_value": f[4],
                    "difference": f[5],
                    "tolerance": f[6],
                    "severity": f[7],
                    "confidence": f[8],
                    "evidence_reference": f[9],
                    "recommended_action": f[10]
                })

            return audit

    @classmethod
    def list_audits(cls) -> List[Dict[str, Any]]:
        """Lists all completed shipment audits."""
        with get_db() as conn:
            cursor = conn.cursor()
            cursor.execute(
                "SELECT id, title, status, created_at, summary_json FROM shipment_audits ORDER BY created_at DESC"
            )
            rows = cursor.fetchall()
            return [
                {
                    "id": r[0],
                    "title": r[1],
                    "status": r[2],
                    "created_at": r[3],
                    "summary": json.loads(r[4])
                }
                for r in rows
            ]

    @classmethod
    def export_report_markdown(cls, audit_id: str) -> str:
        """Generates an exportable, standalone Markdown report for an audit."""
        audit = cls.get_audit(audit_id)
        if not audit:
            raise ValueError(f"Audit {audit_id} not found.")

        lines = [
            f"# TradeSloth Shipment Audit Report: {audit['title']}",
            f"**Audit ID:** `{audit['id']}`  ",
            f"**Generated UTC:** {audit['created_at']}  ",
            f"**Overall Status:** `{audit['status'].upper()}`  \n",
            "> " + LEGAL_DISCLAIMER + "\n",
            "## 1. Audited Documents\n",
            "| Filename | Document Type | Extraction Status |",
            "| :--- | :--- | :--- |"
        ]

        summary = audit["summary"]
        for doc in summary.get("documents", []):
            lines.append(f"| {doc['filename']} | {doc['document_type']} | {doc['extraction_status'].upper()} |")

        lines.append("\n## 2. Cross-Document Discrepancy Matrix\n")
        lines.append("| Field | Status | Difference | Severity | Evidence | Recommended Action |")
        lines.append("| :--- | :--- | :--- | :--- | :--- | :--- |")

        for f in audit["findings"]:
            diff_str = f.get("difference") or "-"
            ev_clean = f.get("evidence_reference", "").replace("\n", " ")
            lines.append(
                f"| {f['field_name']} | {f.get('status', f['severity']).upper()} | {diff_str} | {f['severity'].upper()} | {ev_clean} | {f['recommended_action']} |"
            )

        lines.append("\n## 3. Extracted Field Values Across Documents\n")
        for f in audit["findings"]:
            lines.append(f"### {f['field_name'].replace('_', ' ').title()}")
            lines.append(f"- **Recommended Action:** {f['recommended_action']}")
            lines.append("- **Values by Document:**")
            for doc_name, val in f.get("extracted_values", {}).items():
                lines.append(f"  - `{doc_name}`: {val}")
            lines.append("")

        return "\n".join(lines)

